#!/usr/bin/env node

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildStaticPublish, DEFAULT_STATIC_PUBLISH_DIR } from './build-static-publish.mjs';
import { collectInlineScriptBodies } from './inline-script-bodies.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const frontendRoot = path.join(repoRoot, 'svelte-frontend');
const viteCli = path.join(frontendRoot, 'node_modules', 'vite', 'bin', 'vite.js');
const stagedPublicDir = path.join(repoRoot, 'dist', 'svelte-public-input');
const CSP_SCRIPT_HASH_PLACEHOLDER = '__PROJECTS_SVELTE_SCRIPT_HASHES__';
const SW_GENERATION_SOURCE = "const CACHE_GENERATION = 'source-dev'; // __PROJECTS_SW_CACHE_GENERATION__";
const SW_BUILD_ASSETS_SOURCE = 'const BUILD_ASSETS = Object.freeze([]); // __PROJECTS_SW_BUILD_ASSETS__';

function collectFiles(directory, files = []) {
	for (const entry of readdirSync(directory, { withFileTypes: true })) {
		const target = path.join(directory, entry.name);
		if (entry.isDirectory()) collectFiles(target, files);
		else if (entry.isFile()) files.push(target);
	}
	return files;
}

function publishedPathForUrl(outputDir, url) {
	const pathname = new URL(url, 'https://static.invalid').pathname;
	let relativePath = pathname === '/' ? 'index.html' : pathname.slice(1);
	if (!path.extname(relativePath)) relativePath = `${relativePath}.html`;
	const target = path.resolve(outputDir, relativePath);
	const relativeTarget = path.relative(outputDir, target);
	if (relativeTarget.startsWith('..') || path.isAbsolute(relativeTarget)) {
		throw new Error(`Service-worker precache URL escapes the static artifact: ${url}`);
	}
	return target;
}

function extractBasePrecacheUrls(workerSource) {
	const block = workerSource.match(/const PRECACHE = Object\.freeze\(\[([\s\S]*?)\]\);/u)?.[1];
	if (!block) throw new Error('Service worker must define one frozen PRECACHE array.');
	return [...block.matchAll(/'([^']+)'/gu)].map((match) => match[1]);
}

function finalizeServiceWorker(outputDir) {
	const workerPath = path.join(outputDir, 'sw.js');
	let workerSource = readFileSync(workerPath, 'utf8');
	if (workerSource.split(SW_GENERATION_SOURCE).length !== 2) {
		throw new Error('Service worker must contain exactly one cache-generation source marker.');
	}
	if (workerSource.split(SW_BUILD_ASSETS_SOURCE).length !== 2) {
		throw new Error('Service worker must contain exactly one build-assets source marker.');
	}

	const clientRoot = path.join(outputDir, '_app');
	if (!existsSync(clientRoot)) throw new Error('Static build did not emit the Svelte client asset directory.');
	const buildAssets = collectFiles(clientRoot)
		.map((file) => `/${path.relative(outputDir, file).split(path.sep).join('/')}`)
		.sort((left, right) => left.localeCompare(right));
	if (buildAssets.length === 0) throw new Error('Static build emitted no client assets for offline precaching.');

	workerSource = workerSource.replace(
		SW_BUILD_ASSETS_SOURCE,
		`const BUILD_ASSETS = Object.freeze(${JSON.stringify(buildAssets)}); // generated by build-svelte-frontend.mjs`
	);

	const precacheUrls = [...new Set([...extractBasePrecacheUrls(workerSource), ...buildAssets])]
		.sort((left, right) => left.localeCompare(right));
	const generationHash = createHash('sha256');
	generationHash.update('worker\0');
	generationHash.update(workerSource, 'utf8');
	generationHash.update('\0');
	for (const url of precacheUrls) {
		const file = publishedPathForUrl(outputDir, url);
		if (!existsSync(file)) throw new Error(`Service-worker precache target is missing: ${url}`);
		generationHash.update(url, 'utf8');
		generationHash.update('\0');
		generationHash.update(readFileSync(file));
		generationHash.update('\0');
	}
	const generation = generationHash.digest('hex').slice(0, 16);
	workerSource = workerSource.replace(
		SW_GENERATION_SOURCE,
		`const CACHE_GENERATION = '${generation}'; // generated by build-svelte-frontend.mjs`
	);
	if (/__PROJECTS_SW_|CACHE_GENERATION = 'source-dev'/u.test(workerSource)) {
		throw new Error('Service-worker finalization left a source-only marker in the static artifact.');
	}
	writeFileSync(workerPath, workerSource, 'utf8');
}

function finalizeStaticCsp(outputDir) {
	const hashes = new Set();
	for (const name of readdirSync(outputDir).filter((entry) => entry.endsWith('.html'))) {
		const html = readFileSync(path.join(outputDir, name), 'utf8');
		for (const body of collectInlineScriptBodies(html)) {
			hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
		}
	}
	if (hashes.size === 0) throw new Error('Static CSP finalization found no inline Svelte bootstrap scripts.');

	const headersPath = path.join(outputDir, '_headers');
	const headers = readFileSync(headersPath, 'utf8');
	if (headers.split(CSP_SCRIPT_HASH_PLACEHOLDER).length !== 2) {
		throw new Error('Static CSP must contain exactly one Svelte script-hash placeholder.');
	}
	writeFileSync(headersPath, headers.replace(CSP_SCRIPT_HASH_PLACEHOLDER, [...hashes].sort().join(' ')), 'utf8');
}

async function buildSvelteFrontend(args) {
	try {
		await buildStaticPublish(stagedPublicDir);
		rmSync(DEFAULT_STATIC_PUBLISH_DIR, { recursive: true, force: true });
		const result = spawnSync(process.execPath, [viteCli, 'build', ...args], {
			cwd: frontendRoot,
			env: { ...process.env, PROJECTS_SVELTE_ASSET_DIR: stagedPublicDir },
			stdio: 'inherit',
			windowsHide: true
		});
		if (result.error) throw result.error;
		if (result.status !== 0) {
			const error = new Error(`Static Svelte build exited with status ${result.status ?? 1}.`);
			error.exitCode = result.status ?? 1;
			throw error;
		}
		finalizeServiceWorker(DEFAULT_STATIC_PUBLISH_DIR);
		finalizeStaticCsp(DEFAULT_STATIC_PUBLISH_DIR);
	} finally {
		rmSync(stagedPublicDir, { recursive: true, force: true });
	}
	process.stdout.write('Built the static WebMCP challenge artifact.\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	try {
		await buildSvelteFrontend(process.argv.slice(2));
	} catch (error) {
		process.stderr.write(`${error?.stack || error}\n`);
		process.exitCode = Number.isInteger(error?.exitCode) ? error.exitCode : 1;
	}
}
